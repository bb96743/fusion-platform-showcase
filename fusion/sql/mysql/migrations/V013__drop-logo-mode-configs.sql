-- ============================================================================
--  V013__drop-logo-mode-configs.sql
--
--  用途：移除「亮/暗双版本」相关的两条配置 —— 该功能已被产品决策移除
--  依赖：V007（system.logo）、V010（system.logo-mode）、V011（system.logo-dark）
--  可重复执行：是（DELETE 结果幂等）
--
--  背景（为什么移除）：
--    最初实现了"项目 Logo 亮暗两版 + 项目配置里手选"的功能。但实际落地后暴露两点：
--      ① **命名有真实歧义** —— "亮版/暗版"指图标自身底色、还是指它配的背景色？
--         两种理解会得出**完全相反**的标注，已实际造成误解（负责人看到"亮版"配深色底时感到矛盾）；
--         更麻烦的是配置值 light 的字面含义是"图标是亮色的"，因此它对应**深色**侧边栏，
--         字面与用途相反，无论怎么改文案都留着一层心智负担。
--      ② **收益低于维护成本** —— 定稿图标是「品牌渐变圆角方盒 + 实心白色火花」，
--         方盒**不透明**，自身与深色侧边栏(#001529，对比 4.35:1/6.63:1)和白底(4.23:1/2.78:1)
--         都有足够反差，**同一张图直接用在两种背景上即可**，本就不需要分版本。
--    故项目负责人决定：**固定使用一种图标，移除开关**。
--
--  本迁移做的事：
--    · 删除 system.logo-mode（V010 建）与 system.logo-dark（V011 建）两条配置行
--    · 保留 system.logo（V007 建）—— 上传功能照旧，只是不再有"版本"概念
--
--  说明：
--    · 这两条 is type=1（系统内置）本不允许通过接口删除，
--      这里走 SQL 直接删是**产品决策下的清理**，不是绕过保护做常规操作。
--    · V010/V011/V012 已执行且受 SHA-256 校验保护，无法回首修改；
--      用新迁移做清理符合项目"迁移只增不改"的约定。
--    · 与 `fusion-init.sql` 的种子段**内容对应**（改一处须同步另一处）。
-- ============================================================================

DELETE FROM `infra_config` WHERE `config_key` IN ('system.logo-mode', 'system.logo-dark');


-- ---------------------------------------------------------------------------
-- 结果自检
-- ---------------------------------------------------------------------------
SELECT CONCAT('system.logo 行数 = ', COUNT(*), '（期望 1，上传功能保留）') AS `自检1_保留上传`
  FROM `infra_config` WHERE `config_key` = 'system.logo';

SELECT CONCAT('剩余的 system.logo* 配置键 = ',
              IFNULL(GROUP_CONCAT(`config_key` ORDER BY `config_key`), '（无）'),
              '（期望只有 system.logo）') AS `自检2_已清理`
  FROM `infra_config` WHERE `config_key` LIKE 'system.logo%';
